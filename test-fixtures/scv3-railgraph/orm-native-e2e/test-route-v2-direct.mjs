import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {RailGraphPack} from '../../../js/railgraph-pack.js';
import {ORMClient} from '../../../js/orm.js';
import {ScheduleV2Router} from '../../../js/schedule-v2-routing.js';
const packDir=path.resolve('test-fixtures/scv3-railgraph/orm-native-e2e/pack-v2-direct');
const manifest=JSON.parse(fs.readFileSync(path.join(packDir,'manifest.json'),'utf8'));
globalThis.__RAILNET_TRACK_PACK__=manifest;
let serial=0;
const pack=new RailGraphPack({basePath:'',scriptLoader:async(src,ctx={})=>{const file=ctx.meta?.file||path.basename(src);await import(pathToFileURL(path.join(packDir,file)).href+`?e2e=${++serial}`);}});
await pack.ready();
const orm=new ORMClient();orm.setRailGraphPack(pack);
let network=0;
orm.fetchArea=async()=>{network++;throw new Error('network forbidden')};
orm.fetchSmallOsmMapArea=async()=>{network++;throw new Error('network forbidden')};
orm.fetchRailwayTiles=async()=>{network++;throw new Error('network forbidden')};
const b=(wayId,lat,lon,segmentIndex=0)=>({wayId:String(wayId),lat,lon,snapLat:lat,snapLon:lon,segmentIndex});
const candidates=await orm.getTrackCandidates(49,8.405,{radiusM:30,limit:4,localOnly:true});
if(candidates[0]?.wayId!=='100') throw new Error('track picker did not use ORM-native pack');
if(candidates[0]?.maxSpeed!==120) throw new Error(`ORM maxspeed not propagated: ${candidates[0]?.maxSpeed}`);
const router=new ScheduleV2Router(orm);
const route=await router.routeBetweenBindings(b(100,49,8.405),b(102,49,8.425),[],{maxSpeed:160});
if(!route?.some(p=>String(p.wayId)==='101')) throw new Error('route missing main continuation 101');
if(route.some(p=>String(p.wayId)==='200')) throw new Error('route wrongly uses siding 200');
if(network!==0) throw new Error(`network calls: ${network}`);
console.log(JSON.stringify({prepared:pack.prepared,network,routePoints:route.length,candidateWay:candidates[0].wayId,candidateMaxSpeed:candidates[0].maxSpeed,source:candidates[0].maxSpeedSource,loadedShards:pack.loadedShards.size}));
